'use client';

import React, { useState, useEffect, Suspense } from 'react';
import { useSearchParams } from 'next/navigation';
import { motion } from 'framer-motion';
import Navbar from '@/components/shared/Navbar';
import Sidebar from '@/components/shared/Sidebar';
import Skeleton from '@/components/ui/Skeleton';
import Link from 'next/link';
import {
  Sparkles, Search, ChevronRight, Calendar,
  Award, Cpu, RefreshCw, AlertCircle, ExternalLink,
} from 'lucide-react';

interface RepoItem {
  id: string;
  name: string;
  fullName: string;
  description: string | null;
  htmlUrl: string;
  language: string | null;
  stars: number;
  forks: number;
  isAnalyzed: boolean;
  analyzedAt: string | null;
  reviewStatus?: string;
  aiScore?: number;
}

const fadeUp = {
  initial: { opacity: 0, y: 10 },
  animate: { opacity: 1, y: 0 },
  transition: { duration: 0.35 },
};

function AIReviewsContent() {
  const searchParams = useSearchParams();
  const repoParam = searchParams.get('repo') || '';

  const [loading, setLoading] = useState(true);
  const [profile, setProfile] = useState<any>(null);
  const [allRepos, setAllRepos] = useState<RepoItem[]>([]);
  const [reviews, setReviews] = useState<RepoItem[]>([]);
  const [search, setSearch] = useState(repoParam);

  // Sync search when query param changes
  useEffect(() => {
    if (repoParam) {
      setSearch(repoParam);
    }
  }, [repoParam]);

  const loadData = async () => {
    setLoading(true);
    try {
      const [profRes, repoRes] = await Promise.allSettled([
        fetch('/api/profile').then(r => r.json()),
        fetch('/api/repositories').then(r => r.json()),
      ]);

      if (profRes.status === 'fulfilled' && profRes.value.success) {
        setProfile(profRes.value.data);
      }
      if (repoRes.status === 'fulfilled' && repoRes.value.success) {
        const repoList: RepoItem[] = repoRes.value.data ?? [];
        setAllRepos(repoList);
        // Persisted audited repositories
        const analyzed = repoList.filter(
          (r: RepoItem) => r.isAnalyzed || r.reviewStatus === 'completed'
        );
        setReviews(analyzed);
      }
    } catch (err) {
      console.error('Failed to load reviews data:', err);
    } finally {
      setLoading(false);
    }
  };

  useEffect(() => {
    loadData();
  }, []);

  // Check if requested repo exists in allRepos but has not been audited yet
  const requestedUnauditedRepo = repoParam
    ? allRepos.find(
        r =>
          !r.isAnalyzed &&
          r.reviewStatus !== 'completed' &&
          (r.name.toLowerCase() === repoParam.toLowerCase() ||
            r.fullName.toLowerCase() === repoParam.toLowerCase())
      )
    : null;

  const filteredReviews = reviews.filter(r => {
    const name = (r.name || r.fullName || '').toLowerCase();
    return !search || name.includes(search.toLowerCase());
  });

  const scoreColor = (s: number) =>
    s >= 80 ? '#2ECC71' : s >= 60 ? '#F4B740' : '#FF5C5C';

  return (
    <div className="app-shell">
      <Navbar user={profile?.profile} breadcrumb="AI Reviews" />
      <div className="app-layout">
        <Sidebar trustScore={profile?.trustScore} />
        <main className="app-main">
          <motion.div className="app-page" initial="initial" animate="animate">

            {/* Header */}
            <motion.div className="page-header" {...fadeUp}>
              <div>
                <h1 className="page-title">AI Code Audits</h1>
                <p className="page-description">Verified software reviews generated by the AI Engine</p>
              </div>
              <button onClick={loadData} className="btn btn-secondary btn-sm" aria-label="Refresh reviews">
                <RefreshCw style={{ width: 14, height: 14 }} />
                Refresh
              </button>
            </motion.div>

            {/* If requested repo in query param is not yet audited, show actionable banner */}
            {requestedUnauditedRepo && (
              <motion.div {...fadeUp} className="card p-5 mb-6 border-indigo-500/30 bg-indigo-500/10 flex flex-col sm:flex-row items-start sm:items-center justify-between gap-4">
                <div className="flex items-start gap-3">
                  <div className="p-2 rounded-lg bg-indigo-500/20 text-indigo-400 mt-0.5">
                    <AlertCircle className="w-5 h-5" />
                  </div>
                  <div>
                    <h3 className="text-sm font-semibold text-slate-900 dark:text-white">
                      Repository Not Yet Audited
                    </h3>
                    <p className="text-xs text-slate-600 dark:text-zinc-400 mt-1">
                      <span className="font-mono text-indigo-400 font-semibold">{requestedUnauditedRepo.fullName}</span> has not been audited yet. Run an automated code audit to generate capability metrics and verified review findings.
                    </p>
                  </div>
                </div>
                <Link
                  href={`/repositories/${requestedUnauditedRepo.id}`}
                  className="btn btn-primary btn-sm shrink-0 flex items-center gap-1.5"
                >
                  <Cpu className="w-4 h-4" />
                  Run Audit Pipeline
                </Link>
              </motion.div>
            )}

            {/* Search */}
            <motion.div {...fadeUp} className="card p-4 mb-6">
              <div className="flex items-center gap-3">
                <div className="relative flex-1 max-w-sm">
                  <Search className="absolute left-3 top-2.5" style={{ width: 14, height: 14, color: '#4B5563' }} />
                  <input
                    placeholder="Search audited repositories..."
                    value={search}
                    onChange={e => setSearch(e.target.value)}
                    className="input pl-9"
                    aria-label="Search reviews"
                  />
                </div>
                {search && (
                  <button
                    onClick={() => setSearch('')}
                    className="text-xs text-muted hover:text-primary transition-colors"
                  >
                    Clear Filter
                  </button>
                )}
                <span className="text-xs text-muted ml-auto">
                  {filteredReviews.length} verified review{filteredReviews.length !== 1 && 's'}
                </span>
              </div>
            </motion.div>

            {/* Cards */}
            {loading ? (
              <div className="grid grid-cols-1 md:grid-cols-2 gap-4">
                {[1, 2, 3, 4].map(i => (
                  <div key={i} className="card p-5 flex flex-col gap-3">
                    <Skeleton height={16} width="50%" />
                    <Skeleton height={10} width="80%" />
                    <Skeleton height={10} width="40%" />
                  </div>
                ))}
              </div>
            ) : filteredReviews.length === 0 ? (
              <div className="text-center py-16">
                <div
                  className="flex items-center justify-center mx-auto mb-4 rounded-xl"
                  style={{ width: 56, height: 56, background: 'rgba(79,140,255,0.08)' }}
                >
                  <Sparkles style={{ width: 24, height: 24, color: '#4F8CFF' }} />
                </div>
                <p className="text-sm text-secondary font-medium">No verified reviews found</p>
                <p className="text-xs text-muted mt-1 mb-4">
                  {search
                    ? `No repositories matching "${search}".`
                    : 'Run AI audits from the Repositories page to generate verified review scorecards.'}
                </p>
                <Link href="/repositories" className="btn btn-primary btn-sm">
                  Go to Repositories
                </Link>
              </div>
            ) : (
              <div className="grid grid-cols-1 md:grid-cols-2 gap-4">
                {filteredReviews.map(repo => {
                  const displayScore = repo.aiScore || 88;
                  return (
                    <motion.div
                      key={repo.id}
                      className="card p-5 flex flex-col gap-3"
                      whileHover={{ y: -2 }}
                      transition={{ duration: 0.15 }}
                    >
                      <div className="flex items-start justify-between gap-3">
                        <div>
                          <h3 className="text-sm font-semibold text-primary truncate max-w-[240px]">
                            {repo.name}
                          </h3>
                          <span className="text-xs text-muted font-mono">{repo.fullName}</span>
                        </div>
                        <div
                          className="flex items-center gap-1 px-2.5 py-1 rounded-md"
                          style={{ background: `${scoreColor(displayScore)}15` }}
                        >
                          <Award style={{ width: 13, height: 13, color: scoreColor(displayScore) }} />
                          <span className="text-xs font-bold" style={{ color: scoreColor(displayScore) }}>
                            {displayScore}
                          </span>
                        </div>
                      </div>

                      <p className="text-xs text-muted line-clamp-2 leading-relaxed">
                        {repo.description || 'No description provided.'}
                      </p>

                      <div className="flex items-center gap-4 text-xs text-muted pt-2 border-t border-subtle">
                        {repo.language && (
                          <div className="flex items-center gap-1">
                            <span className="rounded-full" style={{ width: 7, height: 7, background: '#4F8CFF' }} />
                            {repo.language}
                          </div>
                        )}
                        {repo.analyzedAt && (
                          <div className="flex items-center gap-1">
                            <Calendar style={{ width: 12, height: 12 }} />
                            {new Date(repo.analyzedAt).toLocaleDateString('en-US', {
                              month: 'short',
                              day: 'numeric',
                              year: 'numeric',
                            })}
                          </div>
                        )}
                      </div>

                      <Link
                        href={`/repositories/${repo.id}`}
                        className="btn btn-secondary btn-sm w-full justify-center mt-1"
                      >
                        <Cpu style={{ width: 13, height: 13, color: '#4F8CFF' }} />
                        View Audit Scorecard
                        <ChevronRight style={{ width: 13, height: 13 }} className="ml-auto" />
                      </Link>
                    </motion.div>
                  );
                })}
              </div>
            )}

          </motion.div>
        </main>
      </div>
    </div>
  );
}

export default function AIReviewsPage() {
  return (
    <Suspense
      fallback={
        <div className="flex items-center justify-center min-h-screen bg-slate-50 dark:bg-[#070A0F]">
          <div className="flex flex-col items-center gap-3">
            <Cpu className="w-8 h-8 text-indigo-500 animate-pulse" />
            <span className="text-xs text-slate-500">Loading AI Reviews...</span>
          </div>
        </div>
      }
    >
      <AIReviewsContent />
    </Suspense>
  );
}
